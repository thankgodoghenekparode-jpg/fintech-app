/** Host-mapped presentation models; they are not Escrow wire response DTOs. */
import type { EscrowBusinessTone } from "./my_deals_types";

export interface EscrowDisputeQueueItem {
  readonly id: string;
  readonly caseReferenceLabel: string;
  readonly dealReferenceLabel?: string;
  readonly dealTitle: string;
  readonly disputeTypeLabel?: string;
  readonly valueLabel?: string;
  readonly valueBandLabel?: string;
  readonly ageLabel?: string;
  readonly ageBandLabel?: string;
  readonly statusLabel: string;
  readonly statusTone?: EscrowBusinessTone;
  readonly slaLabel?: string;
  readonly slaTone?: EscrowBusinessTone;
  /** Set only from the host's authoritative SLA assessment. */
  readonly slaBreached?: boolean;
  readonly responsiblePartyLabel?: string;
}

export type EscrowDisputeQueueResult =
  | { readonly state: "ready"; readonly cases: readonly EscrowDisputeQueueItem[] }
  | { readonly state: "empty" }
  | { readonly state: "unavailable" }
  | { readonly state: "restricted" };

export interface EscrowDisputeQueueAdapter {
  /** Host maps the documented GET /backoffice/escrow/disputes response. */
  loadQueue(input: { readonly tenantId: string }): Promise<EscrowDisputeQueueResult>;
}

export interface EscrowDisputeEvidence {
  readonly label: string;
  readonly submittedByLabel?: string;
  readonly submittedAtLabel?: string;
  /** Optional host-provided signed URL. No URL is generated by this feature. */
  readonly signedUrl?: string;
}

export interface EscrowDisputeCaseDetail {
  readonly id: string;
  readonly caseReferenceLabel: string;
  readonly dealReferenceLabel?: string;
  readonly dealTitle: string;
  readonly caseTypeLabel?: string;
  readonly statusLabel: string;
  readonly statusTone?: EscrowBusinessTone;
  readonly summary?: string;
  readonly openedAtLabel?: string;
  readonly updatedAtLabel?: string;
  readonly decisionDeadlineLabel?: string;
  readonly buyerLabel?: string;
  readonly sellerLabel?: string;
  readonly termsSnapshot: readonly { readonly label: string; readonly value: string }[];
  readonly feeOutcomeLabel?: string;
  readonly evidence: readonly EscrowDisputeEvidence[];
  readonly history: readonly {
    readonly label: string;
    readonly description?: string;
    readonly timestampLabel?: string;
  }[];
  readonly canDecide: boolean;
  readonly restrictionMessage?: string;
  readonly requiresSecondReview?: boolean;
  readonly secondReviewSatisfied?: boolean;
  readonly secondReviewStatusLabel?: string;
  readonly appealStatusLabel?: string;
}

export type EscrowDisputeCaseResult =
  | { readonly state: "ready"; readonly detail: EscrowDisputeCaseDetail }
  | { readonly state: "unavailable" }
  | { readonly state: "restricted" };

export type EscrowDecisionOutcome = "RELEASE" | "REFUND" | "SPLIT";

export interface EscrowDisputeCaseAdapter {
  /** Host maps authorized case data; no back-office case-read endpoint is specified. */
  loadCase(input: {
    readonly tenantId: string;
    readonly caseId: string;
  }): Promise<EscrowDisputeCaseResult>;
  /** Host-owned PIN authorization. Returns a token only after authorization. */
  authorizeDecision(input: {
    readonly tenantId: string;
    readonly caseId: string;
  }): Promise<string | null>;
  /** Maps only the documented outcome, optional splitSellerKobo, and rationale. */
  submitDecision(input: {
    readonly tenantId: string;
    readonly caseId: string;
    readonly idempotencyKey: string;
    readonly pinToken: string;
    readonly outcome: EscrowDecisionOutcome;
    readonly splitSellerKobo?: number;
    readonly rationale: string;
  }): Promise<void>;
}

